import { expect, test } from '@playwright/test';
test('日期确认与远程选择：部分写入、迟到请求、失败和卸载', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/demos/interactions');
  await page.getByRole('button', { name: '打开交互验收' }).click();
  const snapshot = page.getByTestId('interactions-snapshot');
  const trigger = page.getByRole('button', { name: '选择日期', exact: true });
  const modal = page.getByRole('dialog', { name: '出行日期' });
  await trigger.click();
  await modal.getByRole('textbox', { name: '开始日期', exact: true }).fill('2028-02-29');
  await page.keyboard.press('Escape');
  await expect(modal).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await expect(snapshot).toContainText('"start": "2028-02-28"');
  await trigger.click();
  await modal.getByRole('textbox', { name: '开始日期', exact: true }).fill('2027-02-29');
  await modal.getByRole('button', { name: '确认日期', exact: true }).click();
  await expect(modal.getByText('请输入有效公历日期（YYYY-MM-DD）')).toBeVisible();
  await expect(snapshot).toContainText('"start": "2028-02-28"');
  await modal.getByRole('button', { name: '取消日期' }).click();
  await page.getByRole('button', { name: '模拟结束端不可写' }).click();
  await trigger.click();
  await modal.getByRole('textbox', { name: '开始日期', exact: true }).fill('2028-02-29');
  await modal.getByRole('textbox', { name: '结束日期', exact: true }).fill('2028-03-02');
  await modal.getByRole('button', { name: '确认日期', exact: true }).click();
  await expect(modal.getByRole('alert')).toContainText('开始日期已更新，结束日期未能更新');
  await expect(snapshot).toContainText('"start": "2028-02-29"');
  await expect(snapshot).toContainText('"endState": null');
  await expect(modal.getByRole('textbox', { name: '结束日期', exact: true })).toHaveValue('');
  await modal.getByRole('button', { name: '取消日期' }).click();
  await page.getByRole('button', { name: '恢复结束端' }).click();
  await trigger.click();
  await modal.getByRole('textbox', { name: '结束日期', exact: true }).fill('2028-03-02');
  await modal.getByRole('button', { name: '确认日期', exact: true }).click();
  await expect(modal).toHaveCount(0);
  await expect(snapshot).toContainText('"end": "2028-03-02"');
  const query = page.getByRole('searchbox', { name: '目的地城市', exact: true });
  const search = async (text: string) => {
    await query.fill(text);
    await page.getByRole('button', { name: '搜索', exact: true }).click();
  };
  await search('旧城');
  await search('新城');
  await expect(page.getByText('#1 · 旧城 · CN · 已撤销交付')).toBeVisible();
  await page.getByRole('button', { name: '返回成功 #2', exact: true }).click();
  await page.getByRole('button', { name: '返回成功 #1', exact: true }).click();
  await expect(page.getByRole('button', { name: '旧城市', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '新城市', exact: true }).click();
  await expect(snapshot).toContainText('"id": "CN:新城"');
  await expect(snapshot).toContainText('"label": "新城市"');
  await search('失败');
  await page.getByRole('button', { name: '返回失败 #3', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: '搜索暂时无法完成' })).toBeVisible();
  await expect(snapshot).toContainText('"id": "CN:新城"');
  await search('空');
  await page.getByRole('button', { name: '返回空列表 #4', exact: true }).click();
  await expect(page.getByText('未找到选项', { exact: true })).toBeVisible();
  await expect(snapshot).toContainText('"id": "CN:新城"');
  await search('过滤前');
  await page.getByRole('button', { name: '返回成功 #5', exact: true }).click();
  await expect(page.getByRole('button', { name: '过滤前市', exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: '国家', exact: true }).selectOption({ label: '美国' });
  await expect(snapshot).toContainText('"city": null');
  await expect(page.getByRole('button', { name: '过滤前市', exact: true })).toHaveCount(0);
  await search('隐藏前');
  await page.getByRole('checkbox', { name: '显示城市搜索' }).uncheck();
  await expect(query).toHaveCount(0);
  await expect(page.getByText('#6 · 隐藏前 · US · 已撤销交付')).toBeVisible();
  await page.getByRole('button', { name: '返回成功 #6', exact: true }).click();
  await page.getByRole('checkbox', { name: '显示城市搜索' }).check();
  await expect(query).toHaveValue('');
  await expect(page.getByRole('button', { name: '隐藏前市', exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
});
