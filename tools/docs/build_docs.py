def render(text: str, source: Path, output: Path) -> str:
    result = sanitize(markdown.markdown(text, extensions=EXTENSIONS, extension_configs={"toc": {"slugify": slugify_unicode}}, output_format="html5"))

    def rewrite(match: re.Match) -> str:
        target = urlsplit(html.unescape(match[1]))
        if target.scheme or target.netloc:
            return match[0]
        resolved = (source.parent / unquote(target.path)).resolve() if target.path else source
        destination = OUTPUTS.get(resolved, resolved)
        fragment = target.fragment or DEFAULT_FRAGMENTS.get(resolved, "")
        path = "" if destination == output else quote(os.path.relpath(destination, output.parent), safe="/.-_")
        suffix = ("?" + target.query if target.query else "") + ("#" + fragment if fragment else "")
        return 'href="' + html.escape(path + suffix, quote=True) + '"'

    return re.sub(r'href="([^"]+)"', rewrite, result)


def decorate(body: str) -> str:
    body = re.sub(r'<pre><code class="language-diagram">(.*?)</code></pre>',
                  lambda match: render_diagram(json.loads(html.unescape(match[1]))), body, flags=re.DOTALL)
    def table(match):
        def row(row_match):
            cell = re.search(r"<td>(.*?)</td>", row_match[0], re.S)
            text = html.unescape(re.sub(r"<[^>]+>", "", cell[1])).strip() if cell else ""
            key = ROW_ID.match(text)
            return row_match[0].replace("<tr>", f'<tr id="{key[0]}">', 1) if key else row_match[0]
        return '<div class="table-wrap">' + re.sub(r"<tr>.*?</tr>", row, match[0], flags=re.S) + '</div>'
    body = re.sub(r"<table>.*?</table>", table, body, flags=re.S)

    def codebox(match: re.Match) -> str:
        language = re.search(r'class="language-([^"]+)"', match[0])
        label = html.escape(language[1].upper()) if language else "示例"
        content = re.search(r"<code[^>]*>(.*?)</code>", match[0], re.S)[1]
        raw = html.unescape(content)
        if language and language[1] == "contract":
            clause = parse_clause(raw, "reading Contract")
            status = {"active": "生效", "proposed": "候选", "accepted": "已确认",
                      "superseded": "已替代", "deprecated": "已废弃", "archived": "历史"}
            title = html.escape(clause["id"])
            applies = html.escape(clause["applies_to"])
            items = "".join(f"<li>{html.escape(rule)}</li>" for rule in clause["requires"])
            return (f'<div class="note"><p><strong>{title}</strong> · {status[clause["status"]]}</p>'
                    f'<p>适用：{applies}</p><ul>{items}</ul></div>')
        if language and language[1] == "mermaid":
            if len(raw) > 50000 or "%%{" in raw or raw.lstrip().startswith("---"):
                raise ValueError("Mermaid: per-diagram configuration/directives are disabled; use the shared strict renderer")
            return '<figure class="architecture-diagram mermaid-figure"><figcaption>Mermaid 图示</figcaption><pre class="mermaid">' + html.escape(raw) + '</pre><p class="mermaid-error" hidden>图表未能渲染；完整源码保留在下方。</p><details><summary>查看 Mermaid 源码</summary><pre><code>' + html.escape(raw) + '</code></pre></details></figure>'
        try:
            lexer = get_lexer_by_name(language[1]) if language else TextLexer()
        except ClassNotFound:
            lexer = TextLexer()
        colored = highlight(raw, lexer, HtmlFormatter(nowrap=True, classprefix="syn-"))
        return '<div class="code-box"><div class="code-head"><span>' + label + '</span><button class="copy" type="button">复制</button></div><pre><code>' + colored + '</code></pre></div>'

    body = re.sub(r"<pre><code(?: [^>]*)?>.*?</code></pre>", codebox, body, flags=re.DOTALL)
    return re.sub(r"<li>\[ \] (.*?)</li>", r'<li><label><input type="checkbox"> \1</label></li>', body, flags=re.DOTALL)


def page(source: Path, output: Path, eyebrow: str) -> str:
    _, text = load_source(source)
    heading = re.search(r"^# (.+)\n", text, re.MULTILINE)
    if not heading:
        raise ValueError(f"Missing document title: {source}")
    title = heading[1]
    rendered = render(text[:heading.start()] + text[heading.end():], source, output)
    matches = list(H2.finditer(rendered))
    sections, toc = [], []
    lead = rendered[:matches[0].start()].strip() if matches else ""
    if lead.startswith('<p>') and lead.endswith('</p>'):
        lead = lead[3:-4]
    for i, match in enumerate(matches, 1):
        anchor, title_html = match.groups()
        section_title = html.unescape(re.sub(r'<[^>]+>', '', title_html))
        end = matches[i].start() if i < len(matches) else len(rendered)
        body = decorate(rendered[match.end():end])
        sections.append(f'<section class="section" id="{anchor}">{section_heading(section_title, i)}\n{body}</section>')
        toc.append((anchor, section_title))
    if not matches:
        lead = ""
        sections.append('<section class="section" id="overview">' + decorate(rendered) + '</section>')
        toc.append(("overview", "主题与读取路径"))
    if source == DOCS / "design/architecture.md":
        glossary = load_source(DOCS / "CONTEXT.md")[1].split('\n## Language\n', 1)[1]
        sections.append('<details class="reference-details" id="glossary"><summary>术语与语义边界（按需查阅）</summary>' + decorate(render(glossary, DOCS / "CONTEXT.md", output)) + '</details>')
        toc.append(("glossary", "术语约定"))
    return GENERATED + render_document(output=output, title=title, body='\n'.join(sections), toc=toc,
                                       eyebrow=eyebrow, lead=lead, source=source)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that reading pages match their sources")
    args = parser.parse_args()
    catalog = build_catalog(OUTPUTS)
    set_catalog(catalog)
    pages = {output: page(source, output, eyebrow) for source, output, eyebrow in PAGES}
    pages.update(index_outputs(catalog))
    inventory = source_inventory()
    pages[INVENTORY] = json.dumps(inventory, ensure_ascii=False, indent=2) + "\n"
    legacy_links = [entry for entry in catalog["redirects"] if entry["from"].startswith("l1-definition-protocol-v1.html#")]
    pages[READING / "l1-definition-protocol-v1.html"] = GENERATED + '<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><title>L1 协议阅读入口</title></head><body><p>协议已按能力拆分，旧书签将跳转到对应主题。</p><a href="l1-definition-protocol.html">L1 协议设计</a>' + ''.join('<span id="' + html.escape(item['from'].split('#')[1], quote=True) + '"></span>' for item in legacy_links) + '<script>const routes=' + json.dumps({item['from'].split('#')[1]: item['url'] for item in legacy_links}, ensure_ascii=False) + ';location.replace(routes[decodeURIComponent(location.hash.slice(1))] || "l1-definition-protocol.html");</script></body></html>\n'
    home = READING_HOME.relative_to(READING).as_posix()
    pages[READING / "index.html"] = GENERATED + f'<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta http-equiv="refresh" content="0;url={home}"><title>Assemble Studio 项目手册</title></head><body><a href="{home}">阅读项目手册</a></body></html>\n'
    stale = []
    for path, content in pages.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        parser.exit(1, "Reading pages need rebuilding:\n" + "\n".join(stale) + "\n")
    subprocess.run([sys.executable, str(DOCS / "validation/create_report.py"), *(["--check"] if args.check else [])], check=True)
    page_count, link_count = check_reading_links()
    report = {
        "id": "READER-BUILD-001", "generated_by": "tools/docs/build_docs.py",
        "counts": {"markdown_documents": len(catalog["documents"]), "typed_records": len(catalog["records"]),
                   "html_files": page_count, "local_links_and_resources": link_count,
                   "source_entries": inventory["total_entries"]},
        "checks": {"metadata_ids_and_references": "passed", "replacement_and_task_dependencies": "passed",
                   "source_anchors_code_and_diagrams": "passed", "local_links_and_unique_anchors": "passed"},
        "limits": ["This report covers deterministic build checks; unit and browser checks are separate.",
                   "Source inventory is not sentence-by-sentence historical review or production engine verification."]}
    report_path = READING / "assets/build-report.json"
    report_text = json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    if args.check:
        if not report_path.exists() or report_path.read_text(encoding="utf-8") != report_text:
            parser.exit(1, "Build report needs rebuilding: docs/reading/assets/build-report.json\n")
    else:
        report_path.write_text(report_text, encoding="utf-8")
    count = len(PAGES) + 1  # The validation atlas shares this shell too.
    print(f"All {count} reading pages and the entry redirect match their sources." if args.check else f"Built {count} reading pages and the entry redirect.")
    print(f"Validated {len(catalog['documents'])} Markdown IDs, {len(catalog['records'])} typed records and {page_count} HTML files / {link_count} local links and resources.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError) as error:
        sys.exit(f"Documentation build failed: {error}")
